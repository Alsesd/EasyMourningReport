#!/usr/bin/env python3
"""Bundle Jinja templates for Cloudflare Workers before deploy.

Run from the repository root:
    python scripts/bundle_templates.py

The app's templates are unchanged. The generated module is used only by the
Workers entry point, where a normal writable filesystem is not available.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_DIRS = (ROOT / "app" / "templates",)
OUTPUT_FILE = ROOT / "src" / "_templates_data.py"


def main() -> None:
    templates: dict[str, str] = {}
    for directory in TEMPLATE_DIRS:
        if not directory.is_dir():
            raise SystemExit(f"Required template directory is missing: {directory}")
        for filepath in sorted(directory.rglob("*")):
            if filepath.is_file() and filepath.suffix.lower() in {".html", ".htm", ".xml", ".txt"}:
                name = filepath.relative_to(directory).as_posix()
                templates[name] = filepath.read_text(encoding="utf-8")

    if not templates:
        raise SystemExit("No templates were found; refusing to generate an empty bundle.")

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '"""Generated by scripts/bundle_templates.py; do not edit manually."""',
        "",
        "TEMPLATES = {",
    ]
    for name, content in sorted(templates.items()):
        lines.append(f"    {name!r}: {content!r},")
    lines.extend(["}", ""])
    OUTPUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Bundled {len(templates)} templates into {OUTPUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
